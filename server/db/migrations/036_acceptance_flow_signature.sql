-- =====================================================================
-- 036 验收流转记录保存签署人签名
--
-- 三方手写签署（工长自检提交、监理审核通过、业主确认通过）按「谁在哪一轮
-- 哪个环节签的」落库。签名必须跟着流转记录走：
--   - 已通过的历史验收单不回填，signature_url 为 NULL；
--   - 驳回不要求签名，驳回记录的 signature_url 保持 NULL；
--   - acceptance.signature_url 继续作为业主签名的兼容字段。
-- =====================================================================

ALTER TABLE `acceptance_flow`
  ADD COLUMN `signature_url` VARCHAR(512) NULL
    COMMENT '本次流转的签署人手写签名图片；驳回/历史记录为 NULL'
    AFTER `esign_task_id`;
