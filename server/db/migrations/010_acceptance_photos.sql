-- 010 验收单的现场照片
--
-- C-3.2 要求「发起验收：选择阶段或工序，填写验收说明，**上传现场照片**」，
-- AC-A18 要求验收报告 PDF「内容含验收项、**现场照片**、各级审核意见与签名」。
-- 但 §6.1 的三张验收表里没有承载这些照片的地方：
--   acceptance       无媒体字段
--   acceptance_item  只有验收项本身
--   acceptance_flow  只放**流转环节**附带的照片（AC-A12 的驳回照片）
--
-- 发起验收时上传的现场照片不属于任何一个流转环节，因此加在 acceptance 上。
-- 用 JSON 而非独立表，与 `ledger.receipt_images` 的处理一致：
-- 这些照片只在「属于哪张验收单」这一个维度上被读取，
-- 独立成表要多一次 JOIN，而没有任何查询会单独按照片检索。
--
-- 结构：[{"url":"...","watermarkUrl":"..."}]
-- 水印复用进度汇报那一套（服务端叠加），理由同 AC-P12。
-- =====================================================================

ALTER TABLE `acceptance`
  ADD COLUMN `photos` JSON NULL
    COMMENT '发起验收时上传的现场照片，结构 [{"url":"...","watermarkUrl":"..."}]'
    AFTER `description`;
