-- =====================================================================
-- 019 考察计划：保存路线折线
--
-- 需求文档 §4.6 的 route_plan / route_plan_point 表保存了坐标与分段里程，
-- 但没有折线的持久化字段。路线页需要「地图折线 + 顺序列表」双视图（C-6.6），
-- 若每次打开已保存计划都重新调用地图接口：
--   1. 反复消耗计费配额；
--   2. 道路数据变化后，保存时看到的路线和再次打开时不一致。
--
-- 因此把高德返回的折线快照存下来。格式为 JSON 数组：
--   [{"latitude": 31.23, "longitude": 121.47}, ...]
--
-- 项目坐标变更后，routePlan.service 会把计划标记为「需重新规划」（AC-N10），
-- 此时不返回旧折线 —— 旧折线画在旧坐标上会让人以为路线仍然有效。
-- =====================================================================

ALTER TABLE `route_plan`
  ADD COLUMN `path_json` MEDIUMTEXT NULL
  COMMENT '地图路线折线快照（JSON 数组）；项目坐标变更后不再返回，避免误导'
  AFTER `plan_hash`;
