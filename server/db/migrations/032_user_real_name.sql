-- =====================================================================
-- 032 用户真实姓名
--
-- 昵称（nickname）来自微信，通常是网名；项目列表、联系人、验收记录等
-- 协作场景需要展示真实姓名。真实姓名与昵称分开存储：
--   - 昵称仍由微信 / 用户自己维护；
--   - 真实姓名由用户在小程序「我的 → 个人资料」填写；
--   - 展示优先级统一为 real_name → nickname → 脱敏手机号。
--
-- 不在注册时强制填写：用户可能先被邀请进项目，之后再补资料。
-- =====================================================================

ALTER TABLE `user`
  ADD COLUMN `real_name` VARCHAR(50) NULL
    COMMENT '真实姓名，由用户自己填写；展示时优先于昵称'
    AFTER `nickname`;
